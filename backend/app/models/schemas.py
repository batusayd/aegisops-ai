from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


# ==============================================================================
# 1. ROUTER TELEMETRY & COST TRACKING SCHEMAS
# ==============================================================================

class ModelTier(str, Enum):
    FAST_ROUTER = "FAST_ROUTER"
    REASONING_DRAFT = "REASONING_DRAFT"


class LLMCallMetrics(BaseModel):
    model_config = ConfigDict(extra="forbid")

    call_id: str = Field(..., description="Unique identifier for the LLM call")
    task_type: str = Field(
        ...,
        description="Operation name (e.g., INTENT_CLASSIFICATION, RAG_DRAFT, TOXICITY_MODERATION, CONTEXT_TRANSLATION, DAILY_DIGEST)",
    )
    tier: ModelTier = Field(..., description="Routing tier selected by AI Router")
    model_used: str = Field(..., description="Actual model identifier invoked")
    baseline_model: str = Field(
        default="gpt-4o", description="Single-model baseline compared against"
    )
    input_tokens: int = Field(..., ge=0)
    output_tokens: int = Field(..., ge=0)
    latency_ms: float = Field(..., ge=0.0)
    baseline_latency_ms: float = Field(..., ge=0.0)
    latency_saved_ms: float = Field(..., description="Latency reduction vs single reasoning model")
    actual_cost_usd: float = Field(..., ge=0.0)
    baseline_cost_usd: float = Field(..., ge=0.0)
    cost_saved_usd: float = Field(..., description="USD saved vs running all tasks on baseline reasoning model")
    is_fallback_simulation: bool = Field(
        default=False,
        description="True if generated by deterministic offline demo engine when no live API key is set",
    )
    timestamp: datetime = Field(default_factory=datetime.utcnow)


class GlobalTelemetrySummary(BaseModel):
    model_config = ConfigDict(extra="forbid")

    total_calls: int = 0
    fast_tier_calls: int = 0
    reasoning_tier_calls: int = 0
    total_input_tokens: int = 0
    total_output_tokens: int = 0
    total_actual_cost_usd: float = 0.0
    total_baseline_cost_usd: float = 0.0
    total_cost_saved_usd: float = 0.0
    cost_savings_percentage: float = 0.0
    avg_latency_ms: float = 0.0
    avg_baseline_latency_ms: float = 0.0
    total_latency_saved_ms: float = 0.0
    active_fast_model: str = "gpt-4o-mini"
    active_reasoning_model: str = "gpt-4o"
    recent_calls: List[LLMCallMetrics] = Field(default_factory=list)


# ==============================================================================
# 2. WORKFLOW A: INTELLIGENT SUPPORT TRIAGE, RAG & HITL SCHEMAS
# ==============================================================================

class TicketState(str, Enum):
    INGESTED = "INGESTED"
    CLASSIFIED = "CLASSIFIED"
    DRAFTED = "DRAFTED"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED_AND_SENT = "APPROVED_AND_SENT"
    REJECTED = "REJECTED"
    ESCALATED = "ESCALATED"


class TicketCategory(str, Enum):
    BILLING_REFUND = "BILLING_REFUND"
    TECHNICAL_SUPPORT = "TECHNICAL_SUPPORT"
    ACADEMIC_PROGRAM = "ACADEMIC_PROGRAM"
    ACCOUNT_SECURITY = "ACCOUNT_SECURITY"
    GENERAL_INQUIRY = "GENERAL_INQUIRY"


class UrgencyLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class SentimentType(str, Enum):
    POSITIVE = "POSITIVE"
    NEUTRAL = "NEUTRAL"
    FRUSTRATED = "FRUSTRATED"
    ANGRY = "ANGRY"


class IntentClassification(BaseModel):
    """Strict structured output schema for Fast Router Intent Classification."""
    model_config = ConfigDict(extra="forbid")

    category: TicketCategory = Field(..., description="Primary support ticket category")
    urgency: UrgencyLevel = Field(..., description="Triage urgency level")
    sentiment: SentimentType = Field(..., description="Detected customer sentiment")
    requires_human_escalation: bool = Field(
        ...,
        description="True if policy requires human escalation (e.g., refund > $500, chargeback threat, production outage)",
    )
    detected_language: str = Field(default="EN", description="ISO language code of the ticket")
    key_entities: List[str] = Field(
        default_factory=list, description="Extracted policy codes, error codes, monetary amounts, or domains"
    )
    triage_reasoning: str = Field(
        ..., description="Concise explanation of why this category and urgency were selected"
    )


class KBCitation(BaseModel):
    """Retrieved Vector DB chunk citation."""
    model_config = ConfigDict(extra="forbid")

    chunk_id: str
    doc_id: str = Field(..., description="Document identifier e.g. POL-REF-2026")
    source_file: str = Field(..., description="Source filename in seed/ or uploaded")
    section_ref: str = Field(..., description="Specific policy section code e.g. POL-REF-2026#SEC-2.1")
    title: str
    snippet: str
    similarity_score: float = Field(..., ge=0.0, le=1.0)


class RAGDraftOutput(BaseModel):
    """Strict structured output schema for Reasoning LLM RAG Draft Agent."""
    model_config = ConfigDict(extra="forbid")

    draft_reply: str = Field(
        ..., description="Customer-ready response grounded in retrieved knowledge base chunks with inline citations"
    )
    citations: List[str] = Field(
        ..., description="List of explicit policy/runbook section identifiers cited in the draft"
    )
    confidence_score: float = Field(
        ..., ge=0.0, le=1.0, description="Model confidence in the accuracy and policy compliance of the draft"
    )
    suggested_subject: str = Field(..., description="Suggested email reply subject line")
    resolution_summary: str = Field(
        ..., description="Internal note for the HITL operator explaining the policy applied"
    )


class TicketWebhookPayload(BaseModel):
    """Incoming support ticket payload via Webhook or Simulator."""
    model_config = ConfigDict(extra="forbid")

    customer_name: str = Field(..., min_length=1, max_length=120)
    customer_email: str = Field(..., min_length=3, max_length=160)
    subject: str = Field(..., min_length=3, max_length=250)
    body: str = Field(..., min_length=10, max_length=8000)
    channel: Literal["EMAIL", "WEBHOOK", "PORTAL", "DEMO_SIMULATOR"] = "WEBHOOK"
    metadata: Dict[str, Any] = Field(default_factory=dict)


class StateTransitionLog(BaseModel):
    model_config = ConfigDict(extra="forbid")

    from_state: Optional[TicketState] = None
    to_state: TicketState
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    actor: str = "AI_ORCHESTRATOR"
    note: str = ""


class DispatchedEmailRecord(BaseModel):
    """Simulated outbound email dispatch generated upon HITL approval."""
    model_config = ConfigDict(extra="forbid")

    dispatch_id: str
    ticket_id: str
    to_name: str
    to_email: str
    from_email: str = "support-ops@omnihub.ai"
    subject: str
    final_body: str
    citations_included: List[str]
    approved_by: str
    approval_method: Literal["DASHBOARD_INLINE", "MAGIC_LINK_TOKEN", "AUTO_APPROVED"]
    edited_before_send: bool = False
    dispatched_at: datetime = Field(default_factory=datetime.utcnow)
    cryptographic_audit_hash: str


class TicketRecord(BaseModel):
    """Complete Support Ticket lifecycle object stored in state engine."""
    model_config = ConfigDict(extra="forbid")

    ticket_id: str
    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)
    state: TicketState = TicketState.INGESTED
    state_history: List[StateTransitionLog] = Field(default_factory=list)
    payload: TicketWebhookPayload
    classification: Optional[IntentClassification] = None
    retrieved_chunks: List[KBCitation] = Field(default_factory=list)
    rag_draft: Optional[RAGDraftOutput] = None
    mandatory_human_review: bool = False
    mandatory_review_reasons: List[str] = Field(default_factory=list)
    confidence_threshold_applied: float = 0.75
    action_token_approve: Optional[str] = None
    action_token_reject: Optional[str] = None
    approve_magic_link: Optional[str] = None
    reject_magic_link: Optional[str] = None
    dispatched_email: Optional[DispatchedEmailRecord] = None
    operator_notes: Optional[str] = None
    reviewed_by: Optional[str] = None
    llm_metrics: List[LLMCallMetrics] = Field(default_factory=list)


class TicketReviewRequest(BaseModel):
    """Operator review submission from the HITL Dashboard."""
    model_config = ConfigDict(extra="forbid")

    action: Literal["APPROVE", "REJECT", "ESCALATE"]
    edited_reply: Optional[str] = Field(
        default=None, description="Optional inline-edited response body before dispatching"
    )
    edited_subject: Optional[str] = None
    operator_name: str = Field(default="Lead AI Operations Engineer")
    operator_notes: Optional[str] = None


class ThresholdUpdateRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    confidence_threshold: float = Field(..., ge=0.1, le=0.99)


# ==============================================================================
# 3. WORKFLOW B: MULTILINGUAL COMMUNITY CHAT & MODERATION SCHEMAS
# ==============================================================================

class SupportedLanguage(str, Enum):
    EN = "EN"
    PL = "PL"
    TR = "TR"


class ModerationResult(BaseModel):
    """Strict structured output schema for Fast Router Toxicity & Safety Moderation."""
    model_config = ConfigDict(extra="forbid")

    is_safe: bool = Field(..., description="False if message violates safety/community guidelines")
    toxicity_score: float = Field(..., ge=0.0, le=1.0, description="0.0 (benign) to 1.0 (severe toxicity)")
    flagged_reason: Optional[str] = Field(
        default=None, description="Explanation if toxicity_score >= threshold or policy triggered"
    )
    categories_triggered: List[str] = Field(
        default_factory=list,
        description="E.g. ['HARASSMENT', 'PROFANITY', 'PHISHING_LINK', 'THREAT']",
    )
    action_taken: Literal["ALLOWED", "FLAGGED_WARNING", "BLOCKED_QUARANTINED"] = "ALLOWED"


class TranslationBundle(BaseModel):
    """Context-aware translations across English, Polish, and Turkish."""
    model_config = ConfigDict(extra="forbid")

    original_language: SupportedLanguage
    en: str = Field(..., description="English translation (or original if EN)")
    pl: str = Field(..., description="Polish translation (or original if PL)")
    tr: str = Field(..., description="Turkish translation (or original if TR)")
    context_resolution_note: str = Field(
        ...,
        description="How the sliding window of the last 5 messages helped disambiguate pronouns, technical terms, or tone",
    )


class ChatMessageCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    author_name: str = Field(..., min_length=1, max_length=80)
    author_handle: str = Field(default="@community_member", max_length=60)
    author_role: str = Field(default="Developer", max_length=60)
    language: SupportedLanguage = SupportedLanguage.EN
    content: str = Field(..., min_length=1, max_length=2000)
    channel: str = Field(default="#global-dev-support")


class ChatMessageRecord(BaseModel):
    model_config = ConfigDict(extra="forbid")

    message_id: str
    created_at: datetime = Field(default_factory=datetime.utcnow)
    author_name: str
    author_handle: str
    author_role: str
    channel: str
    original_language: SupportedLanguage
    original_content: str
    moderation: ModerationResult
    translations: TranslationBundle
    sliding_window_context_size: int = Field(
        ..., description="Number of preceding messages injected into the translation context window"
    )
    sliding_window_preview: List[str] = Field(
        default_factory=list, description="Short preview of preceding messages used for context"
    )
    llm_metrics: List[LLMCallMetrics] = Field(default_factory=list)


class DailyDigestReport(BaseModel):
    """Strict structured output for Reasoning LLM Automated Daily Community Digest."""
    model_config = ConfigDict(extra="forbid")

    digest_id: str
    generated_at: datetime = Field(default_factory=datetime.utcnow)
    trigger_type: Literal["MANUAL_TRIGGER", "APSCHEDULER_CRON"] = "MANUAL_TRIGGER"
    period_label: str = "Last 24 Hours — Global Community Channels (EN / PL / TR)"
    total_messages_analyzed: int
    safe_messages_count: int
    flagged_messages_count: int
    language_breakdown: Dict[str, int]
    executive_summary: str
    top_technical_topics: List[str]
    unresolved_member_questions: List[str]
    moderation_incidents_summary: str
    recommended_engineering_actions: List[str]
    llm_metrics: Optional[LLMCallMetrics] = None
